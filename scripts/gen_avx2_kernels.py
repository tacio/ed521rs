"""Generate crates/ed521/src/backend/vector/avx2/kernels.rs: unrolled 4-way multiply and square.

LLVM keeps the triangular loops of a schoolbook product rolled, which leaves the AVX2 multiply no
faster than the serial one; written out, each column is a straight chain of ``vpmuludq`` and
``vpaddq``. Usage:

    python -I scripts/gen_avx2_kernels.py [--check]

Limbs are radix 2^29, 18 of them, and 2^522 = 2 mod p. The bounds argument is in field.rs.
"""

import argparse
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "crates/ed521/src/backend/vector/avx2/kernels.rs"
N = 18


def chain(terms):
    """The sum of ``terms`` as a balanced tree of adds (short dependency chains)."""
    while len(terms) > 1:
        pairs = [f"_mm256_add_epi64({a}, {b})" for a, b in zip(terms[::2], terms[1::2])]
        terms = pairs + ([terms[-1]] if len(terms) % 2 else [])
    return terms[0]


def mul_columns():
    lines = []
    for k in range(N):
        terms = [f"_mm256_mul_epu32(a[{i}], b[{k - i}])" for i in range(k + 1)]
        terms += [f"_mm256_mul_epu32(a[{i}], b2[{k + N - i}])" for i in range(k + 1, N)]
        lines.append(f"        {chain(terms)},\n")
    return lines


def square_columns():
    lines = []
    for k in range(N):
        terms = []
        if k % 2 == 0:
            terms.append(f"_mm256_mul_epu32(a[{k // 2}], a[{k // 2}])")
        terms += [f"_mm256_mul_epu32(d[{i}], a[{k - i}])" for i in range((k + 1) // 2)]
        wrapped = k + N
        if wrapped % 2 == 0 and wrapped // 2 < N:
            terms.append(f"_mm256_mul_epu32(d[{wrapped // 2}], a[{wrapped // 2}])")
        terms += [
            f"_mm256_mul_epu32(q[{i}], a[{wrapped - i}])" for i in range(k + 1, (wrapped + 1) // 2)
        ]
        lines.append(f"        {chain(terms)},\n")
    return lines


def render():
    out = [
        "// @generated by scripts/gen_avx2_kernels.py; do not edit by hand.\n",
        "// The proptests in field.rs compare both kernels with the serial field.\n\n",
        "use core::arch::x86_64::{__m256i, _mm256_add_epi64, _mm256_mul_epu32};\n\n",
        "/// Columns of `a · b`: `z_k = Σ_{i+j=k} a_i b_j + Σ_{i+j=k+18} a_i b2_j`, `b2 = 2b`.\n",
        '#[target_feature(enable = "avx2")]\n',
        "#[inline]\n",
        f"pub(crate) fn mul_columns(a: &[__m256i; {N}], b: &[__m256i; {N}], "
        f"b2: &[__m256i; {N}]) -> [__m256i; {N}] {{\n",
        "    [\n",
        *mul_columns(),
        "    ]\n}\n\n",
        "/// Columns of `a²`, with `d = 2a` and `q = 4a`.\n",
        '#[target_feature(enable = "avx2")]\n',
        "#[inline]\n",
        f"pub(crate) fn square_columns(a: &[__m256i; {N}], d: &[__m256i; {N}], "
        f"q: &[__m256i; {N}]) -> [__m256i; {N}] {{\n",
        "    [\n",
        *square_columns(),
        "    ]\n}\n",
    ]
    return "".join(out)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if OUTPUT.read_text() != text:
            sys.exit(f"{OUTPUT} differs from the regenerated kernels")
        print(f"{OUTPUT.name}: kernels match")
        return
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
