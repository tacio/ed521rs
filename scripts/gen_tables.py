"""Generate crates/ed521/src/tables/generated.rs: curve constants and fixed-base tables.

The values are computed here with Python integers, independently of the Rust arithmetic; a Rust
test recomputes every table from the base point and requires equality. Usage:

    python -I scripts/gen_tables.py [--check]

Field elements are written as nine radix-2^58 limbs (little-endian, the top limb 57 bits) in
canonical form. Scalars are nine little-endian 64-bit words.
"""

import argparse
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "crates/ed521/src/tables/generated.rs"

P = 2**521 - 1
D = -376014 % P
L = int(
    "1716199415032652428745475199770348304317358825035826352348615864796385795849413675475876"
    "651663657849636693659065234142604319282948702542317993421293670108523"
)
BASE_X = int(
    "1571054894184995387535939749894317568645297350402905821437625181152304994381188529632591"
    "196067604100772673927915114267193389905003276673749012051148356041324"
)
BASE_Y = 12

# Fixed-base tables: BASE_ODD[j] holds the odd multiples 1, 3, ..., 127 of [2^(CHUNK j)]B, the
# lookups of wNAF digits (width <= 8) at positions CHUNK j ... CHUNK j + CHUNK - 1. A scalar below
# 2^520 split into CHUNKS chunks needs CHUNK doublings.
CHUNK = 130
CHUNKS = 4
ENTRIES = 64


def add(p, q):
    """Affine Edwards addition (a = 1)."""
    (x1, y1), (x2, y2) = p, q
    t = D * x1 * x2 * y1 * y2 % P
    x3 = (x1 * y2 + y1 * x2) * pow(1 + t, -1, P) % P
    y3 = (y1 * y2 - x1 * x2) * pow(1 - t, -1, P) % P
    return x3, y3


def multiply(k, p):
    result = (0, 1)
    while k:
        if k & 1:
            result = add(result, p)
        p = add(p, p)
        k >>= 1
    return result


def limbs(value):
    assert 0 <= value < P
    return [(value >> (58 * i)) & ((1 << 58) - 1) for i in range(9)]


def words(value, count=9):
    return [(value >> (64 * i)) & ((1 << 64) - 1) for i in range(count)]


def fe(value):
    return "FieldElement([" + ", ".join(f"0x{v:015x}" for v in limbs(value)) + "])"


def affine_cached(point):
    x, y = point
    return (
        f"    AffineCached {{\n        x: {fe(x)},\n        y: {fe(y)},\n"
        f"        xy2d: {fe(D * x * y % P)},\n    }},\n"
    )


def render():
    base = (BASE_X, BASE_Y)
    assert (BASE_X**2 + BASE_Y**2 - 1 - D * BASE_X**2 * BASE_Y**2) % P == 0
    assert multiply(L, base) == (0, 1)
    out = [
        "// @generated by scripts/gen_tables.py; do not edit by hand.\n",
        "// A Rust test (tables::tests) recomputes every value from the base point.\n\n",
        "use super::BaseTables;\n",
        "use crate::backend::serial::curve_models::AffineCached;\n",
        "use crate::backend::serial::field::FieldElement;\n\n",
        "/// The base point's affine x coordinate.\n",
        '#[cfg(any(test, feature = "__bench"))]\n',
        f"pub(crate) const BASE_X: FieldElement = {fe(BASE_X)};\n",
        "/// The base point's affine y coordinate (12).\n",
        '#[cfg(any(test, feature = "__bench"))]\n',
        f"pub(crate) const BASE_Y: FieldElement = {fe(BASE_Y)};\n",
        "/// d = -376014 mod p.\n",
        f"pub(crate) const D: FieldElement = {fe(D)};\n",
        "/// The prime order L of the base point, as little-endian 64-bit words.\n",
        "pub(crate) const L: [u64; 9] = [" + ", ".join(f"0x{w:016x}" for w in words(L)) + "];\n",
        "/// 2^519 - L (258 bits): 2^519 is congruent to it modulo L.\n",
        "pub(crate) const L_FOLD: [u64; 5] = ["
        + ", ".join(f"0x{w:016x}" for w in words(2**519 - L, 5))
        + "];\n",
    ]
    out.append(
        f"/// Bits per chunk of a split scalar.\npub(crate) const CHUNK: usize = {CHUNK};\n"
        f"/// Number of chunks: CHUNK · CHUNKS covers every wNAF position of a scalar below L.\n"
        f"pub(crate) const CHUNKS: usize = {CHUNKS};\n"
    )
    out.append(
        f"\n/// `BASE_ODD.0[j][i]` = [(2i + 1) · 2^({CHUNK} j)]B.\n"
        f"pub(crate) static BASE_ODD: BaseTables = BaseTables([\n"
    )
    point = base
    for _ in range(CHUNKS):
        twice, current = add(point, point), point
        out.append("[\n")
        for _ in range(ENTRIES):
            out.append(affine_cached(current))
            current = add(current, twice)
        out.append("],\n")
        point = multiply(1 << CHUNK, point)
    out.append("]);\n")
    return "".join(out)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if OUTPUT.read_text() != text:
            sys.exit(f"{OUTPUT} differs from the regenerated tables")
        print(f"{OUTPUT.name}: tables match")
        return
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
